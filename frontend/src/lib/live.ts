/**
 * Состояние потока событий (SSE). Пока он подключён, данные приходят мгновенно, а опрос сервера — редкий.
 * Если поток не работает (прокси буферизует, обрыв сети), экраны кухни/кассы/официантов сами переходят на частый опрос.
 */
let live = false;
export const setLive = (v: boolean) => { live = v; };
export const isLive = () => live;

/** refetchInterval для живых данных (заказы, столы): 15 с страховки при работающем SSE, 1 с без него — реакция остаётся мгновенной. */
export const liveInterval = () => (live ? 15_000 : 1_000);
